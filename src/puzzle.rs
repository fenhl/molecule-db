use std::fmt;

macro_rules! puzzles {
    ($($name:literal, $variant:ident, $url:expr,)*) => {
        #[derive(Clone, Copy)]
        pub(crate) enum Puzzle {
            $($variant,)*
        }

        impl Puzzle {
            pub(crate) fn as_str(&self) -> &'static str {
                match self {
                    $(Self::$variant => $name,)*
                }
            }

            pub(crate) fn url(&self) -> Option<&'static str> {
                match self {
                    $(Self::$variant => $url,)*
                }
            }
        }
    };
}

impl Puzzle {
    pub(crate) fn is_custom(&self) -> bool {
        self.url().is_some()
    }
}

impl fmt::Display for Puzzle {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.as_str().fmt(f)
    }
}

